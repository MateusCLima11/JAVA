public class Ex03 {
    public static void main(String[] args) {
        for(int i = 1; i <= 100; i++) {
            if(i % 2 == 0) {
                System.out.println("Os números pares são: " + i);
            } else {
                System.out.println("Os números ímpares são: " + i);
            }
        }
    }
}
