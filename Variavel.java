public class Variavel {

    public static void main(String[] args) {
        
        String nome = "Mateus";
        int idade = 20;
        float altura = 1.80f;
        double nota = 9.5;
        char sexo = 'M';
        
        // concatenação de variáveis
        System.out.println("Olá "+nome+", você tem "+idade+" anos, sua altura é "+altura+" metros, sua nota é "+nota+" e seu sexo é "+sexo+".");
    }
}
