public class ParImpar100 {
    public static void main(String[] args) {
        System.out.println("--- Números Ímpares (1 a 51) ---");
        for (int i = 1; i <= 51; i += 2) {
            System.out.println(i);
        }

        System.out.println("\n--- Números Pares (52 a 100) ---");
        for (int i = 52; i <= 100; i += 2) {
            System.out.println(i);
        }
    }
}