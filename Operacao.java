public class Operacao {
    public static void main(String[] args) {
        int nota1 = 7;
        int nota2 = 8;
        int subtracao = nota1 - nota2;
        int multiplicacao = nota1 * nota2;
        int divisao = nota1 / nota2;
        
        int media = (nota1 + nota2) / 2;
        System.out.println("A média das notas é: " + media);
        System.out.println("A subtração das notas é: " + subtracao);
        System.out.println("A multiplicação das notas é: " + multiplicacao);
        System.out.println("A divisão das notas é: " + divisao);
    }
}
